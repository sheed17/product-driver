"""Run one adaptive-divergence experiment against the real buggy fixture app.

  python run_experiment.py <defect> <port> <outdir> --driver <path> --work <path>
                           [--real] [--no-evidence]

Wave 1 is the identical scripted batch in every run, executed for real against
the app, so the failures fed to wave 2 are observed rather than asserted.
Wave 2 is generated by the real `LLMScenarioReasoner` through the driver's own
`ScenarioPlanner.expand_after_failures`, i.e. the production path.

`--no-evidence` is the control: wave 2 runs with the failure evidence removed
entirely.

Certification additions over the prior campaign's script: wall-clock timing,
explicit capture of generation-session errors as INFRASTRUCTURE observations
(kept separate from product defects), and the full rejection detail so the RAW
and ACCEPTED populations can be compared honestly.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
import traceback
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("defect")
    ap.add_argument("port", type=int)
    ap.add_argument("outdir")
    ap.add_argument("--driver", required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--real", action="store_true")
    ap.add_argument("--no-evidence", action="store_true")
    # The failure evidence quotes the artifact directory, so a run directory
    # named after the seeded defect leaks the defect name into the wave-2 brief.
    # `--label` lets a de-confounded arm run under a neutral identity.
    ap.add_argument("--label", default="")
    args = ap.parse_args()
    label = args.label or args.defect

    import harness

    harness.load_driver(args.driver)

    from neyma_product_driver.scenario_generator import LLMScenarioReasoner

    outdir = Path(args.outdir).resolve()
    outdir.mkdir(parents=True, exist_ok=True)
    work = Path(args.work).resolve()
    store = outdir / "store.json"
    if store.exists():
        store.unlink()

    infra: list[dict] = []

    class CapturingReasoner:
        """Wave 1 scripted; wave 2 delegated to the real model."""

        def __init__(self) -> None:
            self.calls = 0
            self.session_id = ""
            self.wave2_seconds = 0.0
            self._llm = (
                LLMScenarioReasoner(work, model="opus", timeout_s=900)
                if args.real
                else None
            )

        def propose(self, brief):
            self.calls += 1
            rendered = brief.render()
            (outdir / f"brief-wave{self.calls}.txt").write_text(rendered)
            if self.calls == 1:
                return harness.WAVE1_PAYLOAD
            if self._llm is None:
                return None
            started = time.monotonic()
            try:
                payload = self._llm.propose(brief)
            except Exception as exc:  # INFRASTRUCTURE, not a product defect
                self.wave2_seconds = time.monotonic() - started
                infra.append(
                    {
                        "kind": type(exc).__name__,
                        "message": str(exc),
                        "seconds": round(self.wave2_seconds, 1),
                        "traceback": traceback.format_exc(),
                    }
                )
                raise
            self.wave2_seconds = time.monotonic() - started
            self.session_id = self._llm.session_id or ""
            (outdir / f"wave{self.calls}-raw-payload.json").write_text(
                json.dumps(payload, indent=2) if payload is not None else "null"
            )
            if payload is None:
                infra.append(
                    {
                        "kind": "EmptyResponse",
                        "message": "reasoner returned None",
                        "seconds": round(self.wave2_seconds, 1),
                    }
                )
            return payload

    reasoner = CapturingReasoner()
    planner = harness.make_planner(reasoner, args.defect, args.port, store, work)

    t0 = time.monotonic()
    print(f"=== {args.defect}: WAVE 1 (generic, defect-blind) ===", flush=True)
    planner.plan_initial(
        task=harness.TASK, unit=harness.Unit(), run_id=f"cert-{label}"
    )
    (outdir / "wave1-scenarios.json").write_text(
        json.dumps([s.model_dump(mode="json") for s in planner.plan.scenarios], indent=2)
    )

    evidence: list = []
    clusters: list = []
    failures: list = []

    if args.no_evidence:
        print(f"=== {args.defect}: WAVE 2 (CONTROL — evidence withheld) ===", flush=True)
    else:
        print(
            f"=== {args.defect}: EXECUTING WAVE-1 SUITE AGAINST THE REAL APP ===",
            flush=True,
        )
        result, suite, results = await harness.run_suite(
            planner, args.defect, args.port, store, work, outdir / "artifacts-w1"
        )
        (outdir / "wave1-suite-result.json").write_text(
            json.dumps(result.model_dump(mode="json"), indent=2)
        )
        print(result.summary_block(), flush=True)

        failures = result.failures()
        clusters = list(result.clusters)
        (outdir / "wave1-failures.txt").write_text(
            "\n".join(f.brief() for f in failures)
        )
        (outdir / "wave1-clusters.txt").write_text(
            "\n\n".join(c.render() for c in clusters)
        )

        from neyma_product_driver.scenario_suite import build_failure_evidence

        evidence = build_failure_evidence(
            suite, result, results, diff_files=["fixture/app.py"]
        )
        (outdir / "wave1-evidence.txt").write_text(
            "\n\n".join(e.render() for e in evidence)
        )
        print(
            f"=== {args.defect}: WAVE 2 (adaptive from {len(failures)} failure(s)) ===",
            flush=True,
        )

    t_wave1 = time.monotonic() - t0
    before = {s.id for s in planner.plan.scenarios}
    error = ""
    try:
        planner.expand_after_failures(
            task=harness.TASK,
            unit=harness.Unit(),
            failures=evidence,
            clusters=clusters,
            investigation_findings=[],
            evaluator_requests=(
                ["Please verify the approval endpoint more thoroughly."]
                if args.no_evidence
                else []
            ),
            diff_files=["fixture/app.py"],
        )
    except Exception as exc:
        error = f"{type(exc).__name__}: {exc}"
        print(f"!!! wave 2 raised: {error}", flush=True)

    new = [s for s in planner.plan.scenarios if s.id not in before]
    (outdir / "wave2-scenarios.json").write_text(
        json.dumps([s.model_dump(mode="json") for s in new], indent=2)
    )
    (outdir / "plan.json").write_text(
        json.dumps(planner.plan.model_dump(mode="json"), indent=2)
    )
    wave2_records = [w for w in planner.plan.waves if w.wave == 2]
    (outdir / "meta.json").write_text(
        json.dumps(
            {
                "defect": args.defect,
                "no_evidence": args.no_evidence,
                "wave1_failures": [f.scenario_id for f in failures],
                "wave1_failure_briefs": [f.brief() for f in failures],
                "wave1_clusters": [c.cluster_id for c in clusters],
                "wave2_accepted": len(new),
                "wave2_refused": sum(len(w.rejected) for w in wave2_records),
                "wave2_rejections": [
                    {"id": r.id, "reasons": list(r.reasons)}
                    for w in wave2_records
                    for r in w.rejected
                ],
                "wave2_reasoner_error": "; ".join(
                    w.reasoner_error for w in wave2_records if w.reasoner_error
                ),
                "wave2_budget_notes": [n for w in wave2_records for n in w.budget_notes],
                "expand_exception": error,
                "session_id": reasoner.session_id,
                "wave1_seconds": round(t_wave1, 1),
                "wave2_seconds": round(reasoner.wave2_seconds, 1),
                "infrastructure_observations": infra,
            },
            indent=2,
        )
    )

    print(f"wave 2 produced {len(new)} accepted scenario(s):", flush=True)
    for s in new:
        print(f"  [{s.priority.value} {s.risk_category.value}] {s.id}: {s.title}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
